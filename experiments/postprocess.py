"""Derive plotting tables from the raw experiment outputs in results/."""
import os
import sys

import pandas as pd

out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "results")
LABELS = {
    "none": "No monitoring",
    "report_referenced": "AI vs.\\ decision",
    "concordance": "Concordance",
    "delayed_truth": "Delayed truth",
    "dual_audit_3pct_sent2": "Audit 3\\% + sentinels",
    "dual_audit_10pct_sent2": "Audit 10\\% + sentinels",
    "dual_truth_sent2": "Delayed truth + sentinels",
}
ORDER = list(LABELS)

for f in os.listdir(out):
    if f.startswith("e4_state_") and f.endswith(".csv") and "_rel" not in f:
        d = pd.read_csv(os.path.join(out, f))
        b = d.iloc[0]
        for col in ("concordance", "ai_error", "v"):
            d[f"rel_{col}"] = 100 * (d[col] / b[col] - 1)
        d["disagreement"] = 1 - d["concordance"]
        d["rel_disagreement"] = 100 * (d["disagreement"] / (1 - b["concordance"]) - 1)
        d["stack_R0"] = d["R0"]
        d.to_csv(os.path.join(out, f.replace(".csv", "_rel.csv")), index=False)

s = pd.read_csv(os.path.join(out, "e4_summary.csv"))
for sc, g in s.groupby("scenario"):
    g = g.set_index("strategy").loc[ORDER].reset_index()
    g["idx"] = range(len(g) - 1, -1, -1)
    g["label"] = [LABELS[k] for k in g.strategy]
    g["err_lo"] = (g["excess_per_100k_mean"] - g["excess_per_100k_p2.5"]).clip(lower=0)
    g["err_hi"] = (g["excess_per_100k_p97.5"] - g["excess_per_100k_mean"]).clip(lower=0)
    g["int_mid"] = 0.5 * (g["excess_per_100k_p2.5"] + g["excess_per_100k_p97.5"])
    g["int_half"] = 0.5 * (g["excess_per_100k_p97.5"] - g["excess_per_100k_p2.5"])
    g[["idx", "strategy", "label", "excess_per_100k_mean", "excess_per_100k_p2.5",
       "excess_per_100k_p97.5", "err_lo", "err_hi", "int_mid", "int_half",
       "detect_A", "detect_B"]].to_csv(os.path.join(out, f"e4_bars_{sc}.csv"), index=False)

# LaTeX table of the E4 summary for the manuscript / supplement
rows = []
for _, r in s.iterrows():
    def fmt_delay(m, q1, q3):
        return "--" if pd.isna(m) else f"{m:.0f} ({q1:.0f}, {q3:.0f})"
    rows.append([r.scenario.replace("_", " "), LABELS[r.strategy],
                 f"{r['excess_per_100k_mean']:.0f} [{r['excess_per_100k_p2.5']:.0f}, {r['excess_per_100k_p97.5']:.0f}]",
                 f"{r.detect_A:.2f}", fmt_delay(r.delay_A_median, r.delay_A_q1, r.delay_A_q3),
                 f"{r.detect_B:.2f}", fmt_delay(r.delay_B_median, r.delay_B_q1, r.delay_B_q3),
                 "" if pd.isna(r.attribution_ok) else f"{r.attribution_ok:.2f}"])
with open(os.path.join(out, "e4_table.tex"), "w") as f:
    f.write("% generated by experiments/postprocess.py\n")
    for row in rows:
        f.write(" & ".join(row) + " \\\\\n")
print("postprocessed", out)

